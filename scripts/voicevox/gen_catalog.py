"""Generates server/crates/tts/src/catalog.rs from a VVM release.

Inputs:
  - metas.tsv: output of `cargo run --release --bin metas -- <all .vvm>`
    (file, character, style id, style name, style type)
  - the release's README (voice credits and terms links)
  - the GitHub API (sizes and SHA-256 of each .vvm)

Usage: python gen_catalog.py <metas.tsv> <README.md> <out catalog.rs>
"""
import json
import re
import sys
import urllib.request

VVM_TAG = "0.17.1"
# Singing styles (s0) and the anonymous Nemo voices (n0, separate terms) are left out.
SKIP = {"s0.vvm", "n0.vvm"}

metas_path, readme_path, out_path = sys.argv[1:4]

with urllib.request.urlopen(f"https://api.github.com/repos/VOICEVOX/voicevox_vvm/releases/tags/{VVM_TAG}") as r:
    assets = {a["name"]: a for a in json.load(r)["assets"]}

# ---- styles per pack
packs = {}  # file -> {character: [(id, style)]}
seen_ids = {}
for line in open(metas_path, encoding="utf8"):
    file, character, sid, style, kind = line.rstrip("\r\n").split("\t")
    if file in SKIP or not kind.endswith("Talk"):
        continue
    assert sid not in seen_ids, f"style id {sid} in {file} and {seen_ids[sid]}"
    seen_ids[sid] = file
    packs.setdefault(file, {}).setdefault(character, []).append((int(sid), style))

# ---- credits and terms from the README (one "## <character>" section each)
readme = open(readme_path, encoding="utf8").read()
characters = {}
for m in re.finditer(r"^## (.+?)\n(.*?)(?=^## |\Z)", readme, re.S | re.M):
    name, body = m.group(1).strip(), m.group(2)
    credit = re.search(r"「(VOICEVOX:[^」]+)」", body)
    url = re.search(r"^(https?://\S+)", body, re.M)
    if not credit or not url:
        continue
    notes = []
    if "非商用（" in body and "商用・非商用" not in body:
        notes.append("somente uso não comercial")
    if "個人が" in body:
        notes.append("empresas precisam consultar o autor antes")
    if "を除いて" in body:
        notes.append("não vale para obras de áudio, materiais de áudio e jogos")
    characters[name] = (credit.group(1), url.group(1), "; ".join(notes))

# Characters the README has no section for (terms link from voicevox.hiroshiba.jp/product/...).
characters.setdefault("雨晴はう", ("VOICEVOX:雨晴はう", "https://amehau.com/?page_id=225", ""))
# Section titles that differ from the character name in the model metadata.
ALIASES = {}

def rs(s):
    return json.dumps(s, ensure_ascii=False)

def order(f):
    stem = f.removesuffix(".vvm")
    return int(stem) if stem.isdigit() else 999

out = [
    "//! Generated by scripts/voicevox/gen_catalog.py from voicevox_vvm "
    + VVM_TAG + ". Do not edit by hand.",
    "",
    "use super::{Character, Style, VoicePack};",
    "",
    "pub const PACKS: &[VoicePack] = &[",
]
for file in sorted(packs, key=order):
    a = assets[file]
    names = ", ".join(rs(c) for c in packs[file])
    out.append(
        f"    VoicePack {{ file: {rs(file)}, url: {rs(a['browser_download_url'])}, size: {a['size']}, "
        f"sha256: {rs(a['digest'].removeprefix('sha256:'))}, characters: &[{names}] }},"
    )
out += ["];", "", "pub const STYLES: &[Style] = &["]
for file in sorted(packs, key=order):
    for character, styles in packs[file].items():
        for sid, style in styles:
            out.append(f"    Style {{ id: {sid}, character: {rs(character)}, name: {rs(style)}, pack: {rs(file)} }},")
out += ["];", "", "pub const CHARACTERS: &[Character] = &["]
missing = []
for character in dict.fromkeys(c for p in packs.values() for c in p):
    info = characters.get(ALIASES.get(character, character))
    if not info:
        missing.append(character)
        continue
    credit, url, note = info
    out.append(f"    Character {{ name: {rs(character)}, credit: {rs(credit)}, terms_url: {rs(url)}, note: {rs(note)} }},")
out += ["];", ""]
assert not missing, f"no credit in README for: {missing}"

open(out_path, "w", encoding="utf8", newline="\n").write("\n".join(out))
print(f"{len(packs)} packs, {len(seen_ids)} styles, {len(characters)} characters with credits")
